#!/usr/bin/env pwsh
#Requires -Version 7.4

<#
.SYNOPSIS
    Writes containers.json: the public address of every container app of this system, per environment, read from the
    environments' stacks. It changes nothing.

.DESCRIPTION
    The same file carries everything each resource group of the system holds (resources.<key>[], one list per entry of
    system.json azure.resourceGroups: the tiers' groups and any other, such as a group of the system's own Container
    Apps environment), whatever its environment tag, which the runtime diagram draws so that it shows the entire
    system and not only the apps the registry declares (the vault, the identities, the telemetry, the SQL server, a
    container app nobody declared, whatever the system adds in infra/own): the deploy identity of one tier reads its
    own group only, and this script runs as the plan identity, which reads every group. A container app's record also
    has its public address and its Container Apps environment, read from Azure Resource Manager like the list (Reader
    is enough). Every record has its health, which the dashboard shows on the resource's box: what Azure Resource
    Health says of it (one list of Microsoft.ResourceHealth availabilityStatuses per group, read with Reader), and
    where it has no answer (a type it does not cover, or Unknown) the provisioning state the list gave.

    A container app's address is generated by the platform (ca-<slug>-<env>-<deployable>.<environment>.<region>
    .azurecontainerapps.io): no convention names it, and only the environment's stack knows it. The dashboard's
    deployment draws the apps in its runtime diagram from the stacks, but the deploy identity of one tier may not read
    the stacks of the other (production is separated from non-production), so the dashboard of production could not
    draw the apps of tdd and uat, nor the dashboards of tdd and uat those of production. This script runs in the
    workflow "delivery" as the plan identity, which reads every environment's stack, and the file is published next to
    delivery.json on branch "status", where the dashboard's deployment reads what it cannot read itself
    (https://raw.githubusercontent.com/<org>/<repository>/status/containers.json).

    environments.<env>.<deployable>   the address https://<fqdn> the environment's stack reports for the app
    resources.<key>[]                 {type, name, environment, environments, location, id, group, address,
                                      managedEnvironment, health} of every resource of the group
                                      azure.resourceGroups.<key> names; environment is its environment tag ('' without
                                      one), environments the same tag as a set (a shared resource names every
                                      environment it serves, "tdd,uat"), address and managedEnvironment are '' but for
                                      a container app
    resources.<key>[].health          {status, source, checkedAt, summary}: status available, degraded or unavailable
                                      with source resourceHealth (and Resource Health's own words in summary, without
                                      markup, at most 200 characters); else the provisioning state in lower case
                                      ("succeeded") with source provisioningState; else unknown with source none.
                                      checkedAt is when this run read it

    An environment whose stack cannot be read keeps what -Published (the file published now) says of it, with a SKIP
    line, so a refused read never takes an app off the picture; so does a group whose Resource Health is not read,
    for the health of each resource. Only when no stack at all can be read, and the published file has nothing for
    them either, the run fails and writes nothing.

.EXAMPLE
    pwsh -NoProfile -File write-containers.ps1 -Path ./containers.json -Published ./containers.published.json
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [string] $Path,
    # The containers.json published now, as the workflow hands it over; may be absent.
    [string] $Published = '',
    [string] $Root = (Split-Path -Parent $PSScriptRoot)
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true

function Write-Pass { param([string] $Message) Write-Host "PASS $Message" }
function Write-Skip { param([string] $Message) Write-Host "SKIP $Message" }

function Get-ContainerAddress {
    # The container apps of one stack's output "deployables" (an array of { name, hosting, url }), as name -> address.
    # Only an app with an https address counts.
    param([AllowNull()] $Deployable)
    $found = [ordered] @{}
    foreach ($entry in @($Deployable | Where-Object { $_ -is [Collections.IDictionary] })) {
        if ([string] $entry['hosting'] -ne 'containerapp') { continue }
        $address = ([string] $entry['url']).TrimEnd('/')
        if ($entry['name'] -and $address -match '^https://[^/\s]+$') { $found[[string] $entry['name']] = $address }
    }
    return $found
}

function Add-ContainerAppFact {
    # The public address and the Container Apps environment of the container apps among the listed resources, in one
    # read; a refused read leaves them without, with a SKIP line.
    param([object[]] $Item, [string] $Group)
    $ids = @($Item | Where-Object { [string] $_['type'] -ieq 'Microsoft.App/containerApps' -and $_['id'] } | ForEach-Object { [string] $_['id'] })
    if ($ids.Count -eq 0) { return }
    $PSNativeCommandUseErrorActionPreference = $false
    $answer = @(az resource show --ids $ids --only-show-errors --output json 2>&1 | ForEach-Object { "$_" })
    $code = $LASTEXITCODE
    $PSNativeCommandUseErrorActionPreference = $true
    if ($code -ne 0 -or -not ($answer -join '').Trim()) {
        $reason = if ($answer.Count -gt 0) { ($answer[0] -split "`n")[0] } else { "exit code $code" }
        Write-Skip "the container apps of $Group are not read ($reason): they are listed without their addresses"
        return
    }
    $byId = @{}
    foreach ($shown in @(($answer -join "`n") | ConvertFrom-Json -AsHashtable | Where-Object { $_ -is [Collections.IDictionary] })) {
        $properties = if ($shown['properties'] -is [Collections.IDictionary]) { $shown['properties'] } else { @{} }
        $configuration = if ($properties['configuration'] -is [Collections.IDictionary]) { $properties['configuration'] } else { @{} }
        $ingress = if ($configuration['ingress'] -is [Collections.IDictionary]) { $configuration['ingress'] } else { @{} }
        $byId[([string] $shown['id']).ToLowerInvariant()] = @{
            address            = if ($ingress['external'] -eq $true -and $ingress['fqdn']) { "https://$([string] $ingress['fqdn'])" } else { '' }
            managedEnvironment = if ($properties['managedEnvironmentId']) { [string] $properties['managedEnvironmentId'] } elseif ($properties['environmentId']) { [string] $properties['environmentId'] } else { '' }
        }
    }
    foreach ($entry in $Item) {
        $fact = $byId[([string] $entry['id']).ToLowerInvariant()]
        if (-not $fact) { continue }
        $entry['address'] = $fact.address
        $entry['managedEnvironment'] = $fact.managedEnvironment
    }
}

function Add-ResourceHealth {
    # The health of each listed resource of one group, as its record's "health": what Azure Resource Health says of it
    # (the group's list of availability statuses, paged, with Reader), else the provisioning state the list gave
    # (-Provisioned, by lower-case id), else unknown. A refused read keeps the published health of a resource (-Kept,
    # by lower-case id), with a SKIP line.
    param([object[]] $Item, [string] $Group, [hashtable] $Provisioned, [hashtable] $Kept)
    if ($Item.Count -eq 0) { return }
    $checkedAt = [datetime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ', [cultureinfo]::InvariantCulture)
    $availability = @{}
    $refusal = ''
    $next = if ([string] $Item[0]['id'] -match '^(/subscriptions/[^/]+)/') { "https://management.azure.com$($Matches[1])/resourceGroups/$Group/providers/Microsoft.ResourceHealth/availabilityStatuses?api-version=2022-10-01" } else { '' }
    if (-not $next) { $refusal = 'the ids name no subscription' }
    $pages = 0
    while ($next -and $pages -lt 20) {
        $pages++
        $PSNativeCommandUseErrorActionPreference = $false
        $reply = @(az rest --method get --url $next --only-show-errors --output json 2>&1 | ForEach-Object { "$_" })
        $code = $LASTEXITCODE
        $PSNativeCommandUseErrorActionPreference = $true
        if ($code -ne 0 -or -not ($reply -join '').Trim()) {
            $refusal = if ($reply.Count -gt 0) { ($reply[0] -split "`n")[0] } else { "exit code $code" }
            break
        }
        $page = ($reply -join "`n") | ConvertFrom-Json -AsHashtable
        foreach ($said in @($page['value'] | Where-Object { $_ -is [Collections.IDictionary] -and $_['properties'] -is [Collections.IDictionary] })) {
            $availability[(([string] $said['id']) -replace '(?i)/providers/Microsoft\.ResourceHealth/availabilityStatuses/current$', '').ToLowerInvariant()] = $said['properties']
        }
        $next = [string] $page['nextLink']
    }
    if ($refusal) { Write-Skip "Resource Health of $Group is not read ($refusal): its resources keep their published health, else their provisioning state" }
    foreach ($entry in $Item) {
        $id = ([string] $entry['id']).ToLowerInvariant()
        $properties = $availability[$id]
        $availabilityState = if ($properties) { ([string] $properties['availabilityState']).ToLowerInvariant() } else { '' }
        if ($availabilityState -in 'available', 'degraded', 'unavailable') {
            $health = [ordered] @{ status = $availabilityState; source = 'resourceHealth'; checkedAt = $checkedAt }
            $summary = (([string] $properties['summary']) -replace '<[^>]*>', '').Trim()
            if ($summary) { $health.summary = if ($summary.Length -gt 200) { $summary.Substring(0, 200) } else { $summary } }
            $entry['health'] = $health
        }
        elseif ($refusal -and $Kept[$id]) { $entry['health'] = $Kept[$id] }
        elseif ($Provisioned[$id]) { $entry['health'] = [ordered] @{ status = ([string] $Provisioned[$id]).ToLowerInvariant(); source = 'provisioningState'; checkedAt = $checkedAt } }
        else { $entry['health'] = [ordered] @{ status = 'unknown'; source = 'none'; checkedAt = $checkedAt } }
    }
}

$system = Get-Content -LiteralPath (Join-Path $Root 'system.json') -Raw | ConvertFrom-Json -AsHashtable
$slug = [string] $system.system.slug
$before = @{}
$publishedDocument = $null
if ($Published -and (Test-Path -LiteralPath $Published -PathType Leaf)) {
    try {
        $text = Get-Content -LiteralPath $Published -Raw | ConvertFrom-Json -AsHashtable
        $publishedDocument = $text
        if ($text['environments'] -is [Collections.IDictionary]) { $before = $text['environments'] }
    }
    catch { Write-Skip "the published containers.json is not read ($($_.Exception.Message))" }
}

$environments = [ordered] @{}
$read = 0
foreach ($environment in @($system.environments)) {
    $name = [string] $environment.name
    $group = [string] $system.azure.resourceGroups[[string] $environment.tier]
    $PSNativeCommandUseErrorActionPreference = $false
    $answer = @(az stack group show --name "stack-$slug-$name" --resource-group $group --query 'outputs.deployables.value' --only-show-errors --output json 2>&1 | ForEach-Object { "$_" })
    $code = $LASTEXITCODE
    $PSNativeCommandUseErrorActionPreference = $true
    if ($code -eq 0 -and ($answer -join '').Trim()) {
        $parsed = ($answer -join "`n") | ConvertFrom-Json -AsHashtable
        $apps = Get-ContainerAddress -Deployable @($parsed)
        $environments[$name] = $apps
        $read++
        Write-Host "  $name`: $($apps.Count) container app(s)"
    }
    elseif ($before[$name] -is [Collections.IDictionary]) {
        $environments[$name] = $before[$name]
        $reason = if ($answer.Count -gt 0) { ($answer[0] -split "`n")[0] } else { "exit code $code" }
        Write-Skip "the stack of $name is not read ($reason): the published addresses stay"
    }
    else {
        $reason = if ($answer.Count -gt 0) { ($answer[0] -split "`n")[0] } else { 'no output deployables' }
        Write-Skip "the stack of $name is not read ($reason) and nothing is published of it"
    }
}

if ($read -eq 0) {
    Write-Host "FAIL no stack of $slug could be read: containers.json is not written"
    exit 1
}

# Everything the resource groups hold, per entry of azure.resourceGroups, whatever its environment tag. A group that
# cannot be listed keeps what was published of it.
$beforeResources = if ($before.Count -gt 0 -and $publishedDocument -and $publishedDocument['resources'] -is [Collections.IDictionary]) { $publishedDocument['resources'] } else { @{} }
$resources = [ordered] @{}
$groupNames = if ($system.azure['resourceGroups'] -is [Collections.IDictionary]) { $system.azure.resourceGroups } else { @{} }
$listedGroups = @{}
foreach ($key in @($groupNames.Keys | ForEach-Object { [string] $_ } | Sort-Object)) {
    $group = [string] $groupNames[$key]
    if (-not $group) { continue }
    # Two entries that name the same group share its list.
    if ($listedGroups.ContainsKey($group)) { $resources[$key] = $listedGroups[$group]; continue }
    $PSNativeCommandUseErrorActionPreference = $false
    $answer = @(az resource list --resource-group $group --query '[].{id:id,type:type,name:name,location:location,environment:tags.environment,provisioningState:provisioningState}' --only-show-errors --output json 2>&1 | ForEach-Object { "$_" })
    $code = $LASTEXITCODE
    $PSNativeCommandUseErrorActionPreference = $true
    if ($code -eq 0 -and ($answer -join '').Trim()) {
        $items = @(($answer -join "`n") | ConvertFrom-Json -AsHashtable | Where-Object { $_ -is [Collections.IDictionary] })
        $provisionedIn = @{}
        foreach ($item in $items) { if ($item['id'] -and $item['provisioningState']) { $provisionedIn[([string] $item['id']).ToLowerInvariant()] = [string] $item['provisioningState'] } }
        $publishedHealth = @{}
        foreach ($old in @(if ($beforeResources[$key] -is [System.Collections.IEnumerable] -and $beforeResources[$key] -isnot [string]) { $beforeResources[$key] })) {
            if ($old -isnot [Collections.IDictionary] -or -not $old['id'] -or $old['health'] -isnot [Collections.IDictionary]) { continue }
            # ConvertFrom-Json reads the time as a date: it is written back in the file's own form.
            if ($old['health']['checkedAt'] -is [datetime]) { $old['health']['checkedAt'] = ([datetime] $old['health']['checkedAt']).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ', [cultureinfo]::InvariantCulture) }
            $publishedHealth[([string] $old['id']).ToLowerInvariant()] = $old['health']
        }
        $records = @($items | Sort-Object { [string] $_['type'] }, { [string] $_['name'] } | ForEach-Object {
                $tag = if ($_['environment']) { [string] $_['environment'] } else { '' }
                [ordered] @{ type = [string] $_['type']; name = [string] $_['name']; environment = $tag; environments = @($tag -split ',' | ForEach-Object { $_.Trim() } | Where-Object { $_ } | Select-Object -Unique); location = [string] $_['location']; id = [string] $_['id']; group = $group; address = ''; managedEnvironment = '' }
            })
        Add-ContainerAppFact -Item $records -Group $group
        Add-ResourceHealth -Item $records -Group $group -Provisioned $provisionedIn -Kept $publishedHealth
        $resources[$key] = $records
        $listedGroups[$group] = $records
        Write-Host "  $key`: $($records.Count) resource(s) in $group"
    }
    elseif ($beforeResources[$key] -is [System.Collections.IEnumerable] -and $beforeResources[$key] -isnot [string]) {
        $resources[$key] = @($beforeResources[$key])
        $reason = if ($answer.Count -gt 0) { ($answer[0] -split "`n")[0] } else { "exit code $code" }
        Write-Skip "the resources of $group are not listed ($reason): the published list stays"
    }
    else { Write-Skip "the resources of $group are not listed and nothing is published of them" }
}

$document = [ordered] @{
    generated    = [datetime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ', [cultureinfo]::InvariantCulture)
    environments = $environments
    resources    = $resources
}
$target = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
[IO.File]::WriteAllText($target, "$($document | ConvertTo-Json -Depth 6)`n")
$total = 0
foreach ($apps in $environments.Values) { $total += @($apps.Keys).Count }
$resourceTotal = 0
$healthTotal = 0
foreach ($listed in $resources.Values) {
    $resourceTotal += @($listed).Count
    $healthTotal += @($listed | Where-Object { $_ -is [Collections.IDictionary] -and $_['health'] -is [Collections.IDictionary] -and $_['health']['source'] -eq 'resourceHealth' }).Count
}
Write-Pass "${target}: $total container app(s) in $($environments.Count) environment(s) of $slug, $resourceTotal resource(s) in $($resources.Count) group(s), $healthTotal of them with Resource Health"
# Said as an exit code: a workflow step ends with the exit code of the last program the script ran (the stack reads
# above may have been refused, and that is handled).
exit 0
